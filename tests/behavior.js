async page => {
  const result=[];
  const wait=id=>page.waitForFunction(x=>!document.querySelector('#lab-'+x+' .primary').disabled,id,{timeout:45000});
  const status=id=>page.locator('#lab-'+id+' .lab-status').textContent();
  const verify=(ok,message)=>{if(!ok)throw new Error(message);result.push(message);};
  await page.locator('#lab-r-ops-code').fill('remainder <- 0\nquotient <- 0');
  await page.locator('#lab-r-ops .primary').click();await wait('r-ops');
  verify((await status('r-ops')).startsWith('0/2'),'R 오답 거절');
  await page.locator('#lab-py-limit-code').fill('def max_n(limit):\n    return 0');
  await page.locator('#lab-py-limit .primary').click();await wait('py-limit');
  verify(!(await status('py-limit')).includes('완료!'),'Python 오답 거절');
  await page.locator('#lab-py-limit-code').fill('def broken(:');
  await page.locator('#lab-py-limit .primary').click();await wait('py-limit');
  verify((await page.locator('#lab-py-limit .lab-output').textContent()).includes('SyntaxError'),'문법 오류 표시');
  await page.locator('#lab-py-limit-code').fill('while True:\n    pass');
  await page.locator('#lab-py-limit .primary').click();
  await page.locator('#lab-py-limit .stop').click();
  verify((await status('py-limit')).includes('중지했습니다'),'Python 수동 중지');
  await page.locator('#lab-r-ops-code').fill('while (TRUE) {}');
  await page.locator('#lab-r-ops .primary').click();
  await page.locator('#lab-r-ops .stop').click();
  verify((await status('r-ops')).includes('중지했습니다'),'R 수동 중지');
  await page.locator('#lab-py-input-code').fill('a,b=map(int,input().split())\ntotal=a+b\nquotient=a//b\nremainder=a%b\nprint(total)');
  await page.locator('#lab-py-input-stdin').fill('20 3');
  await page.locator('#lab-py-input-code').press('Control+Enter');await wait('py-input');
  verify((await status('py-input')).includes('완료!'),'중지 후 재실행·Ctrl+Enter·사용자 입력');
  await page.reload();
  verify((await page.locator('#lab-py-input-code').inputValue()).includes('total=a+b'),'새로고침 후 코드 저장');
  verify((await page.locator('#lab-py-input-stdin').inputValue())==='20 3','새로고침 후 입력 저장');
  await page.locator('#lab-py-limit-code').fill('while True:\n    pass');
  await page.locator('#lab-py-limit .primary').click();await wait('py-limit');
  verify((await status('py-limit')).includes('12초'),'무한 반복 12초 자동 중지');
  const details=page.locator('#lab-py-limit details');
  await details.nth(0).locator('summary').click();
  verify(await details.nth(0).getAttribute('open')!==null,'힌트 펼치기');
  await details.nth(1).locator('summary').click();
  await details.nth(1).getByRole('button').click();
  verify((await page.locator('#lab-py-limit-code').inputValue()).includes('while total + n + 1'),'예시 답안 넣기');
  await page.locator('#lab-py-limit').getByRole('button',{name:'시작 코드로 초기화',exact:true}).click();
  verify((await page.locator('#lab-py-limit-code').inputValue()).includes('return 0'),'시작 코드 초기화');
  return result;
}
